// Regenerates src/content/legalContent.generated.ts from docs/legal/*.
// docs/legal is the single source of truth for legal text; run this after any
// edit there so the in-app screens stay in sync with the hosted documents.
//
//   node scripts/generate-legal-content.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const SOURCES = {
  en: { terms: 'docs/legal/en/terms-of-service.md', privacy: 'docs/legal/en/privacy-policy.md' },
  az: { terms: 'docs/legal/az/istifade-sertleri.md', privacy: 'docs/legal/az/mexfilik-siyaseti.md' },
  ru: { terms: 'docs/legal/ru/usloviya-ispolzovaniya.md', privacy: 'docs/legal/ru/politika-konfidencialnosti.md' },
};

/** Markdown → [{heading?, paragraphs[]}] for simple native rendering. */
function parseSections(markdown) {
  const withoutComments = markdown.replace(/<!--[\s\S]*?-->/g, '');
  const lines = withoutComments.split('\n');

  const sections = [];
  let current = { heading: undefined, paragraphs: [] };
  let buffer = [];

  const flushParagraph = () => {
    const text = buffer.join(' ').replace(/\s+/g, ' ').trim();
    if (text) current.paragraphs.push(text);
    buffer = [];
  };
  const flushSection = () => {
    flushParagraph();
    if (current.heading || current.paragraphs.length) sections.push(current);
  };

  for (const rawLine of lines) {
    const line = rawLine.trimEnd();
    if (/^#\s/.test(line)) {
      // Document title — screens render their own title.
      continue;
    }
    if (/^#{2,3}\s/.test(line)) {
      flushSection();
      current = { heading: inline(line.replace(/^#{2,3}\s+/, '')), paragraphs: [] };
      continue;
    }
    if (/^\s*[-*]\s+/.test(line)) {
      flushParagraph();
      current.paragraphs.push(`• ${inline(line.replace(/^\s*[-*]\s+/, ''))}`);
      continue;
    }
    if (line.trim() === '' || /^---+$/.test(line.trim())) {
      flushParagraph();
      continue;
    }
    buffer.push(inline(line));
  }
  flushSection();
  return sections;
}

/** Strip inline markdown we can't render natively. */
function inline(text) {
  return text
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/`(.+?)`/g, '$1')
    .replace(/\[(.+?)\]\((.+?)\)/g, '$1 ($2)')
    .trim();
}

const result = {};
for (const [locale, docs] of Object.entries(SOURCES)) {
  result[locale] = {};
  for (const [doc, path] of Object.entries(docs)) {
    result[locale][doc] = parseSections(readFileSync(join(root, path), 'utf8'));
  }
}

const output = `// AUTO-GENERATED by scripts/generate-legal-content.mjs — do not edit by hand.
// Source of truth: docs/legal/*. Regenerate after any change there.

export interface LegalSection {
  heading?: string;
  paragraphs: string[];
}

export type LegalDocument = 'terms' | 'privacy';

export const legalContent: Record<'az' | 'en' | 'ru', Record<LegalDocument, LegalSection[]>> =
${JSON.stringify(result, null, 2)};
`;

writeFileSync(join(root, 'src/content/legalContent.generated.ts'), output);
const counts = Object.entries(result)
  .map(([l, docs]) => `${l}: terms ${docs.terms.length}§ / privacy ${docs.privacy.length}§`)
  .join(', ');
console.log(`Wrote src/content/legalContent.generated.ts (${counts})`);
